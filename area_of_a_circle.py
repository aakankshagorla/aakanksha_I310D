def compute_area_of_circle(radius):
	pi = 3.14
	area = pi * radius * radius
	return area

radius_1 = 10
area_1 = compute_area_of_circle(radius_1)
print(f"The area of circle with radius {radius_1} is: {area_1}")

radius_2 = 20
area_2 = compute_area_of_circle(radius_2)
print(f"The area of circle with radius {radius_2} is: {area_2}")
